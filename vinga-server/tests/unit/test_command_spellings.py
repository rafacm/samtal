# The CLI guide is the one page that is both. It states the standard in
# the short spelling and quotes the merged grammar in the long one, as
# counterexamples, audit rows and recorded tensions; the quotes are the
# record and the standard is live. So the page is classified by the
# program word rather than by its path, and this is the rule:
_GUIDE = "docs/architecture/cli-guide.md"

# And its exceptions, which are shapes the page writes in the short
# spelling because the point is the grammar, and which no tree will
# ever answer to: a constructed counterexample is written to be
# rejected. Each is held to still appearing in the page, so an entry
# cannot go stale unnoticed.
_GUIDE_REJECTED = {
    # The address demoted to options, under "Identity addressing".
    "vinga set": "the constructed counterexample of an address written as flags",
}


@dataclass(frozen=True)
class Spelling:
    """One quoted invocation, where it is and what it is."""

    path: str
    line: int
    invocation: str
    kind: str

    def rendered(self) -> str:
        return f"{self.path}:{self.line}  {self.kind}  {self.invocation}"


def tracked() -> list[str]:
    """Every file git tracks, so an untracked scratch file cannot change
    the answer."""
    listed = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=REPO_ROOT,
        capture_output=True,
        check=True,
        text=True,
    )
    return sorted(name for name in listed.stdout.split("\0") if name)


def _text(path: str) -> str | None:
    """One tracked file's text, or None for one that is not text at all.

    A binary file has no command spelling in it, and a decoding failure
    here is a fact about the file rather than about the sweep.
    """
    try:
        return (REPO_ROOT / path).read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return None


def _generated_region(text: str) -> tuple[int, int] | None:
    """The line numbers the generated markers enclose, or None."""
    lines = text.splitlines()
    opened = closed = None
    for number, line in enumerate(lines, start=1):
        if line.strip() == _GENERATED_REGION[0]:
            opened = number
        if line.strip() == _GENERATED_REGION[1]:
            closed = number
    return (opened, closed) if opened is not None and closed is not None else None


def _classified(path: str, program: str, invocation: str, inside: bool) -> str:
    """Which of the three classes one match belongs to.

    Path first, because a generated artifact is generated whatever it
    quotes and a record is a record whatever it quotes. The guide is
    the one page classified by its program word, for the reason stated
    above it.
    """
    if path.startswith(_GENERATED_PATHS) or _GENERATED_DIRECTORY in f"/{path}":
        return "generated"
    if path == _HALF_GENERATED:
        # Generated between the markers and prose outside them, which is
        # what the page says about itself in its own head.
        return "generated" if inside else "respell"
    if path.startswith(_HISTORICAL_PATHS):
        return "historical"
    if path == _GUIDE:
        if invocation in _GUIDE_REJECTED or program != "vinga":
            return "historical"
        return "respell"
    return "respell"


def _command_line(program: str, rest: str, words: frozenset[str]) -> str | None:
    """One match as the invocation it quotes: the program word and every
    bare word after it.

    The words stop at the first token that is not bare, which is where
    an option, a path, a placeholder or a punctuated end of sentence
    begins. Everything up to there is KEPT, addresses included, because
    the tail is what the guard reads: a row can only be held to taking
    what follows it if what follows it is still here.

    A capture that dropped the words it could not place would be the
    scanner deciding the question the guard exists to ask. `vinga list
    agents` is not `vinga list` with a word after it, it is an
    invocation `list` cannot be given, and a scanner that recorded the
    first would report a document as correct on the strength of having
    edited it. So nothing is discarded, and a site whose prose runs into
    a quoted command is fixed at the site.
    """
    typed = rest.split()
    if not typed or typed[0] not in words:
        return None
    taken: list[str] = []
    for word in typed:
        if not _bare(word):
            break
        taken.append(word)
    return " ".join([program, *taken])


def _bare(word: str) -> bool:
    """Whether a token is a bare command word: letters, digits and
    dashes, opening with a letter. An address, an option, a path and a
    placeholder are each something else."""
    return bool(word) and word[0].isalpha() and word.replace("-", "").isalnum()


def retired(words: frozenset[str]) -> frozenset[str]:
    """The compounds the re-cut took away.

    A word the old top level had, that no row and no group of the tree
    carries at any depth, and that this grammar coined by joining two
    words with a hyphen. The last condition is what makes the set
    checkable rather than a list: an ordinary word cannot be in it, and
    a compound nothing answers to any more can be nothing else.
    """
    live = {word for row in cli.COMMANDS for word in row.words}
    live |= {word for path in cli.GROUPS for word in path}
    return frozenset(word for word in _RETIRED_WORDS if "-" in word and word not in live)


def _matches(path: str, text: str, words: frozenset[str]) -> list[Spelling]:
    """Every recognized invocation in one file, and every retired word."""
    found: list[Spelling] = []
    region = _generated_region(text) if path == _HALF_GENERATED else None
    gone = retired(words)
    for number, line in enumerate(text.splitlines(), start=1):
        inside = region is not None and region[0] < number < region[1]
        claimed: list[tuple[int, int]] = []
        for match in _INVOCATION.finditer(line):
            quoted = _command_line(match.group(1), match.group(2).strip(), words)
            if quoted is None:
                continue
            claimed.append(match.span())
            found.append(
                Spelling(
                    path=path,
                    line=number,
                    invocation=quoted,
                    kind=_classified(path, match.group(1), quoted, inside),
                )
            )
        for match in _SHORTHAND.finditer(line):
            if any(start <= match.start() < end for start, end in claimed):
                continue
            quoted = _command_line("config", match.group(2).strip(), words)
            if quoted is None:
                continue
            found.append(
                Spelling(
                    path=path,
                    line=number,
                    invocation=quoted,
                    kind=_classified(path, "config", quoted, inside),
                )
            )
        for match in _RETIRED.finditer(line):
            if match.group(1) not in gone:
                continue
            found.append(
                Spelling(
                    path=path,
                    line=number,
                    invocation=match.group(1),
                    kind=_classified(path, "word", match.group(1), inside),
                )
            )
    return found


def census() -> list[Spelling]:
    """Every command spelling in the tree, in file and line order."""
    words = _command_words()
    found: list[Spelling] = []
    for path in tracked():
        if path == str(MANIFEST.relative_to(REPO_ROOT)):
            continue
        text = _text(path)
        if text is None:
            continue
        found += _matches(path, text, words)
    return found


def manifest() -> str:
    """The census as the committed manifest reads."""
    return MANIFEST_HEADER + "".join(f"{row.rendered()}\n" for row in census())


# The guard
#
# A `respell` match is an invocation a reader is meant to run, so its
# words have to name something the tree has. Which row a command line
# names is `tests.support.config_cli.registered`, the one matcher the
# live lane and the wheel lane read too; what this adds is the other
# thing prose legitimately quotes, which is a group word with no verb
# after it (`the vinga-server config provider secret commands`). A group is
# a node of the same tree, so it is read off the same table.


def _nodes() -> frozenset[tuple[str, ...]]:
    """Every path the registered tree answers to: each row, and each
    group on the way to one."""
    return frozenset(
        row.words[:length]
        for row in cli.COMMANDS
        for length in range(1, len(row.words) + 1)
    )


def _typed(invocation: str) -> tuple[str, ...]:
    """The command words of one invocation: what follows the program
    word."""
    rest = invocation.split()
    for prefix in (("vinga-server", "config"), ("vinga", "config"), ("vinga",), ("config",)):
        if tuple(rest[: len(prefix)]) == prefix:
            return tuple(rest[len(prefix) :])
    return tuple(rest)


def names_something(invocation: str) -> bool:
    """Whether one quoted invocation names a command or a group the
    tree actually has.

    A command is matched by longest registered prefix, because what
    follows its words is an address and an option list. A group is
    matched EXACTLY, because a group takes nothing after it: `vinga
    provider` is a legitimate way for prose to name the noun, and
    `vinga provider frobnicate` is a command that does not exist. A
    leading-prefix rule accepted both, which is the half of this guard
    that was accepting invalid spellings.
    """
    typed = _typed(invocation)
    if registered(typed) is not None:
        return True
    return typed in _nodes()


def test_the_manifest_is_the_census() -> None:
    """The committed classification, held to a fresh scan.

    The manifest is the reviewable half of this sweep, so it is checked
    the way every other generated artifact in this repository is: it is
    rendered again and diffed, and a change to what the tree quotes
    fails here until the manifest is regenerated with it.
    """
    assert MANIFEST.read_text(encoding="utf-8") == manifest()


def test_every_live_spelling_names_a_command_the_tree_has() -> None:
    """The standing guard.

    A `respell` match is an invocation somebody is meant to type. If its
    words do not name a row of the registration table, the document
    naming it is telling a reader to run a command this server does not
    have, which is the failure the whole sweep exists to prevent.
    """
    stale = [
        row.rendered()
        for row in census()
        if row.kind == "respell" and not names_something(row.invocation)
    ]
    assert stale == []


# The half a registered-command guard cannot see
#
# `_command_line` stops at the first token that is not a bare word, so
# `vinga apply -f deployment.yaml` is recorded as `vinga apply`, and the
# guard above then finds `apply` in the tree and passes it. That is the
# right reading for every rename this census had met: a retired word
# stayed retired, so a stale line named nothing.
#
# #371 is the shape that breaks it. It swapped two verbs rather than
# retiring one, so `apply` still names a row and what moved is what the
# row takes: the new `apply` installs the stored configuration and takes
# no document at all. A line left in the old grammar therefore names a
# command that exists and asks it to do something it cannot, which is
# the same failure the census exists to prevent, arriving one layer
# deeper. So the options are read too, off the raw line, for the one
# invocation whose meaning moved.

# What the new `apply` does not take: the document options the old one
# did, and the flag that used to turn its second act off.
_APPLY_REJECTS = ("-f", "--file", "--no-reload")

# One `apply` invocation and everything typed after it, up to where a
# command line ends in prose or in a shell. The tail is the half this
# reads, which is exactly the half the scanner above discards.
_APPLY_TAIL = re.compile(
    r"(?<![\w./-])(?:vinga-server config|vinga config|vinga|config)[ \t]+apply(?![\w-])"
    rf"([^{re.escape(_TERMINATORS)}]*)"
)


def _carries_a_document(line: str) -> bool:
    """Whether one raw line asks an `apply` for something it cannot
    take."""
    return any(
        option in match.group(1)
        for match in _APPLY_TAIL.finditer(line)
        for option in _APPLY_REJECTS
    )


def option_bearing_applies(path: str, text: str) -> list[str]:
    """Every live `apply` in one file written the way the old one was.

    Classified through the same scanner as everything else, so the
    historical records and the generated artifacts are exempt here for
    the reasons they are exempt there.
    """
    lines = text.splitlines()
    return [
        row.rendered()
        for row in _matches(path, text, _command_words())
        if row.kind == "respell"
        and _typed(row.invocation) == ("apply",)
        and _carries_a_document(lines[row.line - 1])
    ]


def test_no_live_apply_is_written_the_way_the_old_one_was() -> None:
    """The standing guard over the stale half of the verb swap."""
    stale = [
        row
        for path in tracked()
        if path != str(MANIFEST.relative_to(REPO_ROOT)) and (text := _text(path)) is not None
        for row in option_bearing_applies(path, text)
    ]

    assert stale == []


def test_a_stale_apply_is_flagged_and_the_new_one_is_not() -> None:
    """The guard held to going red, which is the half a passing
    assertion cannot show: the first three lines are the old grammar
    left behind, and the last two are what replaced it."""
    page = "\n".join(
        [
            "run `vinga apply -f deployment.yaml`",
            "run `vinga-server config apply --file deployment.yaml`",
            "run `vinga apply --no-reload -f -`",
            "run `vinga import -f deployment.yaml`",
            "run `vinga apply`",
        ]
    )

    flagged = option_bearing_applies("docs/somewhere.md", page)

    assert [row.split(":")[1].split(" ")[0] for row in flagged] == ["1", "2", "3"]


def test_the_guides_rejected_shapes_still_appear() -> None:
    """The guide's exemptions, held to being about something.

    An entry naming a shape the page has since stopped writing would
    quietly widen what a `respell` match is allowed to be.
    """
    quoted = {row.invocation for row in census() if row.path == _GUIDE}
    assert sorted(_GUIDE_REJECTED) == sorted(set(_GUIDE_REJECTED) & quoted)


# What a generated document may be spelled as
#
# One spelling, whatever rendered it, which is the rule the whole
# canonical constant exists for: a document may no more vary with the
# invocation than with the terminal. The drift checks cannot see this.
# They regenerate an artifact and diff it, so a description carrying the
# wrong program word moves the committed copy and the fresh render
# together and passes green forever.
#
# One exception, and it is a different fact rather than a loosening.
# `events.md` renders the event catalog's message templates, and those
# are sentences a SERVER composes: a server runs inside the image, where
# `vinga-server` is what a shell answers to, and the settled rule sends
# such a sentence to the long spelling. What is generated there is the
# document, not the sentence.
_SERVER_COMPOSED = ("docs/reference/events.md",)

# And what the rule is not about at all: a captured experiment. The
# spike artifacts under `spikes/` were rendered on the day they were
# run, against the grammar of that day, and nothing regenerates them.
# Holding a frozen capture to today's spelling would be asking a
# photograph to age.
_CAPTURED = ("spikes/",)


def mis_spelled(rows: list[Spelling]) -> list[str]:
    """Every generated invocation that is not in the canonical
    spelling."""
    return [
        row.rendered()
        for row in rows
        if row.kind == "generated"
        and not row.path.startswith(_SERVER_COMPOSED + _CAPTURED)
        and not row.invocation.startswith(f"{cli.PROGRAM} ")
    ]


def test_a_generated_document_carries_one_spelling() -> None:
    """The standing guard over the artifacts this repository renders."""
    assert mis_spelled(census()) == []


def test_the_long_spelling_inside_a_generated_region_is_flagged() -> None:
    """And the guard held to going red, which is the half a passing
    assertion cannot show: this is the text the review round found in
    two committed artifacts, and it is a finding rather than a pass."""
    page = "\n".join(
        [
            _GENERATED_REGION[0],
            "| `tools` | which is the name `vinga-server config status` shows |",
            _GENERATED_REGION[1],
        ]
    )

    flagged = mis_spelled(_matches(_HALF_GENERATED, page, _command_words()))

    assert [row.split("  ")[-1] for row in flagged] == ["vinga-server config status"]


def test_a_server_composed_document_keeps_the_long_spelling() -> None:
    """The exception, held to being one: an event message names the
    invocation a server has, and the guard leaves it alone."""
    page = "device %s has no agent; bind it with: vinga-server config device pending claim"

    assert mis_spelled(_matches("docs/reference/events.md", page, _command_words())) == []


def test_every_class_is_one_of_the_three() -> None:
    """The vocabulary, kept closed. A fourth class would be a
    classification nobody stated a rule for."""
    assert {row.kind for row in census()} <= {"respell", "historical", "generated"}


