"""The conversation store's documentation, rendered from the tables.

One source, two renderings: `comment=` on every column is written once
and read here as the markdown reference committed at
`docs/reference/conversations-schema.md` and as what `vinga-server
conversations schema` prints. The drift test fails on a column with no
comment, which is the same discipline `Field(description=...)` enforces
for the domain models next door.

Everything here is deterministic: no timestamps, no set iteration, and
the column order is the schema's own declaration order. CI regenerates
the committed copy and diffs it byte for byte, so anything that varied
between two runs would turn the lane red on an unrelated change.

Two things a column renderer cannot document, and the honest answer to
each. The event vocabulary that fills `events.name` and `events.fields`
is defined by the event registry, and rendered by the reference beside
this document, which this links rather than restating: fifty-eight
declarations copied here would drift, and the store adds no drift of its
own because it copies field names verbatim. And the
correspondence to OpenTelemetry's GenAI conventions is a mapping
between two vocabularies rather than a property of one column, so it is
written out below where an exporter author reads it once.

Read-only, and deliberately so: nothing here opens a database, reads a
configuration file or needs a key.
"""

